"""List custom GT processing overrides from a checkout of the pinned source tag."""
import argparse
import re
from pathlib import Path

METHODS = re.compile(r"(?:public|protected)\s+(?:final\s+)?(?:boolean|void|int|CheckRecipeResult)\s+"
                     r"(runMachine|onPostTick|checkRecipe|checkProcessing|doCheckRecipe)\s*\(")

parser = argparse.ArgumentParser()
parser.add_argument("source", type=Path)
parser.add_argument("--output", type=Path, default=Path("docs/gt-overrides.md"))
args = parser.parse_args()
rows = []
for file in sorted((args.source / "src/main/java").rglob("*.java")):
    text = file.read_text(encoding="utf-8")
    found = sorted(set(METHODS.findall(text)))
    if found and ("extends MTE" in text or "extends TT" in text):
        rows.append(f"| `{file.stem}` | {', '.join(f'`{x}`' for x in found)} |")
args.output.parent.mkdir(parents=True, exist_ok=True)
args.output.write_text(
    "# GT5-Unofficial 5.09.54.265 override audit\n\n"
    "Generated by `scripts/audit_gt.py` against commit `bb00f3f1023e20d3cce84cf09abb442d22a3a5a5`. "
    "This is a conservative source inventory, not a declaration that these classes are supported. "
    "Runtime coverage requires inherited standard methods and physical inputs; see coverage.md.\n\n"
    "| Class | Declared processing hooks |\n|---|---|\n" + "\n".join(rows) + "\n", encoding="utf-8")
print(f"Audited {len(rows)} classes with processing overrides")
